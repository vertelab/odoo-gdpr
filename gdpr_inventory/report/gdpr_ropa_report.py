import csv
import io
import json

from odoo import api, fields, models, _

ARTICLE30_COLUMNS = [
    ('controller', 'Controller (Art. 30.1(a))'),
    ('dpo', 'Data Protection Officer (Art. 30.1(a))'),
    ('name', 'Processing activity'),
    ('purpose', 'Purposes of processing (Art. 30.1(b))'),
    ('data_subjects', 'Categories of data subjects (Art. 30.1(c))'),
    ('data_types', 'Categories of personal data (Art. 30.1(c))'),
    ('recipients', 'Recipients (Art. 30.1(d))'),
    ('third_countries', 'Third-country transfers (Art. 30.1(e))'),
    ('safeguards', 'Transfer safeguards (Art. 30.1(e))'),
    ('retention', 'Retention limit (Art. 30.1(f))'),
    ('security', 'Security measures (Art. 30.1(g))'),
]


class GdprRopaReport(models.AbstractModel):
    """Article 30 register of processing activities.

    `_rows()` is the single source of truth: the PDF, the CSV export and the
    generation log all read it. If the column set changes, it changes in
    ARTICLE30_COLUMNS and everything follows.
    """

    _name = 'report.gdpr_inventory.gdpr_ropa_report'
    _description = 'GDPR Article 30 Register'

    @api.model
    def _get_inventories(self):
        return self.env['gdpr.inventory'].search([('state', '=', 'active')], order='name')

    @api.model
    def _rows(self):
        rows = []
        for inventory in self._get_inventories():
            rows.append({
                'controller': inventory.company_id.name or '',
                'dpo': inventory.dpo_partner_id.display_name or '',
                'name': inventory.name or '',
                'purpose': inventory.purpose_limitation or '',
                'data_subjects': ', '.join(inventory.data_subject_ids.mapped('name')),
                'data_types': ', '.join(inventory.data_type_ids.mapped('name')),
                'recipients': ', '.join(
                    inventory.recipient_category_ids.mapped('name')
                    + inventory.data_sharing_ids.mapped('name')),
                'third_countries': ', '.join(inventory.third_country_ids.mapped('name')),
                'safeguards': inventory.transfer_safeguards or '',
                'retention': (
                    _('%s months') % inventory.retention_months
                    if inventory.retention_months else ''),
                'security': ', '.join(inventory.security_of_processing_ids.mapped('name')),
            })
        return rows

    @api.model
    def _render(self, report_ref=None):
        rows = self._rows()
        return {
            'doc_ids': self._get_inventories().ids,
            'doc_model': 'gdpr.inventory',
            'docs': self._get_inventories(),
            'columns': ARTICLE30_COLUMNS,
            'rows': rows,
            'generated_at': fields.Datetime.now(),
            'generated_by': self.env.user.name,
            'inventory_count': len(rows),
        }

    @api.model
    def _log_generation(self, count):
        """Record that a register was produced, so an auditor can tie an
        output back to the data that produced it."""
        return self.env['gdpr.ropa.generation'].create({
            'user_id': self.env.user.id,
            'inventory_count': count,
            'generated_at': fields.Datetime.now(),
        })

    @api.model
    def action_export_csv(self):
        rows = self._rows()
        self._log_generation(len(rows))
        buffer = io.StringIO()
        writer = csv.writer(buffer, delimiter=';', quoting=csv.QUOTE_MINIMAL)
        writer.writerow([label for _key, label in ARTICLE30_COLUMNS])
        for row in rows:
            writer.writerow([row[key] for key, _label in ARTICLE30_COLUMNS])
        return {
            'type': 'ir.actions.act_url',
            'url': '/gdpr/ropa.csv',
            'target': 'self',
        }

    @api.model
    def _csv_bytes(self):
        rows = self._rows()
        buffer = io.StringIO()
        writer = csv.writer(buffer, delimiter=';', quoting=csv.QUOTE_MINIMAL)
        writer.writerow([label for _key, label in ARTICLE30_COLUMNS])
        for row in rows:
            writer.writerow([row[key] for key, _label in ARTICLE30_COLUMNS])
        # BOM so Excel opens the semicolon-separated UTF-8 file correctly
        return ('\ufeff' + buffer.getvalue()).encode('utf-8')


class GdprRopaGeneration(models.Model):
    _name = 'gdpr.ropa.generation'
    _description = 'GDPR Article 30 Register Generation'
    _order = 'generated_at desc'

    generated_at = fields.Datetime(
        string='Generated', default=fields.Datetime.now, required=True)
    user_id = fields.Many2one(
        'res.users', string='Generated By', required=True,
        default=lambda self: self.env.user)
    inventory_count = fields.Integer(string='Inventories Included')
    note = fields.Text()
